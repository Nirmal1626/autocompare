import type { Car, Category, Transmission, Variant } from './types';

function pack(
  input: Omit<Car, 'fuels' | 'transmission' | 'variants'> & {
    variants: [string, string, Transmission, number][];
  },
): Car {
  const variants: Variant[] = input.variants.map(([name, fuel, transmission, price]) => ({
    name,
    fuel,
    transmission,
    price,
  }));
  const fuels = Array.from(new Set(variants.map((variant) => variant.fuel)));
  const transmissions = Array.from(new Set(variants.map((variant) => variant.transmission)));
  return {
    ...input,
    variants,
    fuels,
    transmission: transmissions.join(' / '),
  };
}

