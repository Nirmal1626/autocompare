export const brands = Array.from(new Set(cars.map((car) => car.brand)));

export const categories: Category[] = ['SUV', 'Sedan', 'Hatchback'];

export function getCar(slug: string) {
  return cars.find((car) => car.slug === slug);
}

export function startingPrice(car: Car) {
  return Math.min(...car.variants.map((variant) => variant.price));
}

export function carsByBrand(brand?: string) {
  if (!brand) return cars;
  return cars.filter((car) => car.brand === brand);
}

export function categoryImage(category: Category) {
  if (category === 'SUV') return '/cat-suv.jpg';
  if (category === 'Sedan') return '/cat-sedan.jpg';
  return '/cat-hatch.jpg';
}
